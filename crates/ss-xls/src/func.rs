#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_numbers_that_matter_most_are_the_ones_everybody_uses() {
        assert_eq!(lookup(4), Some(("SUM", VAR)));
        assert_eq!(lookup(1), Some(("IF", VAR)));
        assert_eq!(lookup(102), Some(("VLOOKUP", VAR)));
        assert_eq!(lookup(27), Some(("ROUND", 2)));
    }

    #[test]
    fn a_function_this_build_does_not_know_is_reported_rather_than_invented() {
        assert_eq!(lookup(9_999), None);
    }
}
