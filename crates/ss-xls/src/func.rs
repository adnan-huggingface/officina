//! The built-in function table: BIFF stores a function as a number.
//!
//! Two token forms use it. `ptgFuncVar` carries its own argument count, so for
//! those the arity below is never consulted. `ptgFunc` does not — the count is
//! implied by *which* function it is, and a reader that guesses wrong pops the
//! wrong number of operands and silently produces a different formula.
//!
//! So [`VAR`] is used for anything whose fixed arity is not certain. A
//! `ptgFunc` naming one of those makes the whole formula undecompilable, and
//! the cell keeps its cached value instead — a visible gap rather than a
//! plausible wrong answer. In practice this costs nothing, because a function
//! with a variable argument count is always written as `ptgFuncVar`.

